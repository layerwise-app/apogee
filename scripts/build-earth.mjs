// Builds the globe's land data from Natural Earth (public domain,
// https://www.naturalearthdata.com/):
//   src/lib/earth/land-data.ts        land dots for the WebGL globe (a bitset)
//   public/globe-still.svg              the still shown until WebGL is ready
//
// Usage: node scripts/build-earth.mjs
// Downloads ne_50m_land and ne_110m_land into .cache/natural-earth/ once.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { geoBounds, geoContains, geoGraticule, geoOrthographic, geoPath } from 'd3-geo';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const cacheDir = path.join(root, '.cache', 'natural-earth');
const SOURCE =
  'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson';

async function load(name) {
  const file = path.join(cacheDir, `${name}.geojson`);
  if (!fs.existsSync(file)) {
    fs.mkdirSync(cacheDir, { recursive: true });
    const res = await fetch(`${SOURCE}/${name}.geojson`);
    if (!res.ok) throw new Error(`Download failed for ${name}: ${res.status}`);
    fs.writeFileSync(file, Buffer.from(await res.arrayBuffer()));
  }
  return JSON.parse(fs.readFileSync(file, 'utf8'));
}

// Must match ROW_STEP_DEG and the row layout in src/lib/earth/land.ts.
const ROW_STEP_DEG = 0.75;

const land50 = await load('ne_50m_land');
const land110 = await load('ne_110m_land');

// ---- Land dots: rows of equally spaced points, one bit per point ----------
const features = land50.features.map((f) => {
  const [[w, s], [e, n]] = geoBounds(f);
  return { f, w, s, e, n, wraps: w > e };
});

const rows = Math.round(180 / ROW_STEP_DEG);
const bits = [];
let landCount = 0;
const started = Date.now();
for (let r = 0; r < rows; r++) {
  const lat = -90 + (r + 0.5) * ROW_STEP_DEG;
  const count = Math.max(1, Math.round((360 * Math.cos((lat * Math.PI) / 180)) / ROW_STEP_DEG));
  for (let j = 0; j < count; j++) {
    const lon = -180 + ((j + 0.5) * 360) / count;
    let inside = false;
    for (const b of features) {
      if (lat < b.s || lat > b.n) continue;
      if (b.wraps ? lon < b.w && lon > b.e : lon < b.w || lon > b.e) continue;
      if (geoContains(b.f, [lon, lat])) {
        inside = true;
        break;
      }
    }
    bits.push(inside ? 1 : 0);
    if (inside) landCount++;
  }
}
const bytes = new Uint8Array(Math.ceil(bits.length / 8));
bits.forEach((bit, i) => {
  if (bit) bytes[i >> 3] |= 1 << (i & 7);
});
const base64 = Buffer.from(bytes).toString('base64');
fs.writeFileSync(
  path.join(root, 'src/lib/earth/land-data.ts'),
  `// Generated by scripts/build-earth.mjs from Natural Earth ne_50m_land
// (public domain). Do not edit by hand.
export const LAND_ROW_STEP_DEG = ${ROW_STEP_DEG};
export const LAND_POINT_COUNT = ${bits.length};
export const LAND_DOT_COUNT = ${landCount};
export const LAND_BITS =
  '${base64}';
`
);
console.log(
  `land dots: ${landCount} of ${bits.length} points, ${bytes.length} bytes, ${((Date.now() - started) / 1000).toFixed(1)} s`
);

// ---- SVG still for the hero view -------------------------------------------
const viewSrc = fs.readFileSync(path.join(root, 'src/components/globe/hero-view.ts'), 'utf8');
const lon0 = Number(/lon:\s*(-?[\d.]+)/.exec(viewSrc)[1]);
const lat0 = Number(/lat:\s*(-?[\d.]+)/.exec(viewSrc)[1]);
const SIZE = 1000;
const projection = geoOrthographic()
  .rotate([-lon0, -lat0])
  .clipAngle(90)
  .translate([SIZE / 2, SIZE / 2])
  .scale(SIZE / 2)
  .precision(1.2);
const toPath = geoPath(projection).digits(0);
// Drop specks smaller than a few pixels in the still.
const landPath = toPath({
  type: 'FeatureCollection',
  features: land110.features.filter((f) => toPath.area(f) === 0 || toPath.area(f) > 6)
});
const graticulePath = toPath(geoGraticule().step([30, 30])());
const C = SIZE / 2;
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="-20 -20 ${SIZE + 40} ${SIZE + 40}" width="${SIZE + 40}" height="${SIZE + 40}">
<defs>
<radialGradient id="o" cx="38%" cy="36%" r="70%"><stop offset="0" stop-color="#0d1624"/><stop offset=".7" stop-color="#070c15"/><stop offset="1" stop-color="#04070c"/></radialGradient>
<pattern id="d" width="6.5" height="6.5" patternUnits="userSpaceOnUse"><circle cx="3.25" cy="3.25" r="1.25" fill="#7d90a8"/></pattern>
</defs>
<circle cx="${C}" cy="${C}" r="${C}" fill="url(#o)"/>
<path d="${graticulePath}" fill="none" stroke="#9fb4cf" stroke-opacity=".08" stroke-width="1"/>
<path d="${landPath}" fill="url(#d)"/>
<circle cx="${C}" cy="${C}" r="${C + 1}" fill="none" stroke="#8fb6ff" stroke-opacity=".55" stroke-width="1.5"/>
<circle cx="${C}" cy="${C}" r="${C + 6}" fill="none" stroke="#8fb6ff" stroke-opacity=".12" stroke-width="10"/>
</svg>
`;
fs.writeFileSync(path.join(root, 'public/globe-still.svg'), svg);
console.log(`still: land path ${landPath.length} chars, graticule ${graticulePath.length} chars`);
